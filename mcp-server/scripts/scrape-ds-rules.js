const MAX_CHARS = 8000; // per section — enough for rules, not whole design spec

async function extractContent(page) {
  return page.evaluate((maxChars) => {
    const main = document.querySelector("main");
    if (!main) return "";

    const clone = main.cloneNode(true);

    // Drop sidebar nav, tab buttons, feedback forms, code blocks, images.
    clone.querySelectorAll(
      '[role="tree"], nav, .col-sm-3, aside, [role="tablist"], ' +
      'pre, code, figure, img, svg, .feedback, footer, .col-sm-2'
    ).forEach(el => el.remove());

    // Extract headings + their following paragraphs/lists as structured text.
    const blocks = [];
    clone.querySelectorAll("h1, h2, h3, h4, p, li, dt, dd").forEach(el => {
      const text = el.innerText?.trim();
      if (!text || text.length < 3) return;
      const tag = el.tagName.toLowerCase();
      if (tag.startsWith("h")) {
        blocks.push(`\n## ${text}`);
      } else {
        blocks.push(text);
      }
    });

    const full = blocks.join("\n").replace(/\n{3,}/g, "\n\n").trim();

    // Hard cap — take the first maxChars characters and close at a newline.
    if (full.length <= maxChars) return full;
    const cut = full.lastIndexOf("\n", maxChars);
    return full.slice(0, cut > 0 ? cut : maxChars) + "\n\n[… truncated]";
  }, MAX_CHARS);
}

async function scrapeTab(page, url, tab) {
  const target = tab ? `${url}?tab=${tab}` : url;
  await page.goto(target, { waitUntil: "networkidle" });

  // Wait for the main content area to have actual text beyond navigation.
  await page.waitForFunction(() => {
    const main = document.querySelector("main");
    return main && main.innerText.trim().length > 200;
  }, { timeout: 15_000 }).catch(() => {/* use whatever loaded */});

  return extractContent(page);
}

async function main() {
  console.log("Launching browser…");
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext();
  const page    = await context.newPage();

  const result = {
    meta: {
      source: "gov.br Design System — Padrão Digital de Governo",
      url: BASE_URL,
      scrapedAt: new Date().toISOString(),
      note: "Auto-generated by scripts/scrape-ds-rules.js. Re-run to update.",
    },
    categories: {},
  };

  for (const { category, label, url, tabs } of PAGES) {
    console.log(`Scraping: ${label}`);
    const sections = {};

    if (tabs.length === 0) {
      sections.content = await scrapeTab(page, url, null);
    } else {
      for (const tab of tabs) {
        console.log(`  tab: ${tab}`);
        sections[tab] = await scrapeTab(page, url, tab);
      }
    }

    result.categories[category] = { label, url, sections };
  }

  await browser.close();

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, JSON.stringify(result, null, 2), "utf8");

  const categories = Object.keys(result.categories).length;
  console.log(`\nDone. Wrote ${categories} categories to data/ds-page-rules.json`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
